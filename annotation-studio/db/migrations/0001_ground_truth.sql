-- SportReel Ground Truth — protected schema (PostgreSQL 15+, Supabase-compatible).
-- NOT part of supabase/migrations/: it is never applied by the production migration workflow.
-- Applied only by annotation-studio/scripts/gt-migrate.mjs with an explicit admin connection.
-- Placeholder __SCHEMA__ is substituted by the runner (default: ground_truth).

create schema if not exists __SCHEMA__;
set local search_path = __SCHEMA__;

create table if not exists schema_migrations(version text primary key, applied_at timestamptz not null default now());
create table if not exists meta(key text primary key, value text not null);

create table if not exists sources(
  id text primary key,
  sha256 text not null check (sha256 ~ '^[0-9a-f]{64}$'),
  byte_size bigint not null check (byte_size >= 0),
  display_name text not null,
  session_key text,
  codec text, width integer, height integer, rotation integer not null default 0,
  fps_num integer, fps_den integer, frame_count integer, duration_ms bigint,
  captured_at text,
  ingest_state text not null default 'pending_archive'
    check (ingest_state in ('pending_archive','ready','archive_error','unavailable')),
  archive_key text, archive_verified_at text, archive_error text,
  thumb_path text, proxy_path text,
  created_at text not null,
  unique (sha256, byte_size)
);

create table if not exists source_locations(
  id bigint generated by default as identity primary key,
  source_id text not null references sources(id),
  provider text not null, bucket text, key text not null,
  kind text not null check (kind in ('operational','archive','legacy')),
  observed_at text not null, active integer not null default 1, verified_sha256 text
);
create index if not exists source_locations_src on source_locations(source_id);

create table if not exists upload_batches(id text primary key, label text not null, created_at text not null);
create table if not exists upload_occurrences(
  id bigint generated by default as identity primary key,
  source_id text not null references sources(id),
  batch_id text not null references upload_batches(id),
  original_name text not null, location_key text, created_at text not null,
  unique (source_id, batch_id, original_name)
);
create table if not exists ingestion_jobs(
  id bigint generated by default as identity primary key,
  origin_key text not null, batch_id text,
  state text not null check (state in ('queued','running','done','failed')),
  attempts integer not null default 0, error text, source_id text,
  created_at text not null, updated_at text not null,
  unique (origin_key, batch_id)
);

create table if not exists athletes(id text primary key, label text not null, notes text, created_at text not null);
create table if not exists athlete_appearances(
  id text primary key, athlete_id text not null references athletes(id), source_id text not null references sources(id),
  track_label text, uncertain integer not null default 0, confirmed integer not null default 0, created_at text not null,
  unique (athlete_id, source_id)
);

create table if not exists annotation_drafts(
  source_id text primary key references sources(id),
  version integer not null, content text not null, base_revision_id text, updated_at text not null
);
create table if not exists annotation_revisions(
  id text primary key, source_id text not null references sources(id),
  seq integer not null, parent_revision_id text, content text not null, digest text not null,
  author text not null, reason text, schema_version integer not null,
  scope text not null check (scope in ('source','interval','segment')),
  created_at text not null, approved_at text not null,
  unique (source_id, seq)
);

create table if not exists dataset_versions(
  id text primary key, name text not null, created_at text not null, policy text not null, manifest text not null, digest text not null
);
create table if not exists dataset_members(
  dataset_id text not null references dataset_versions(id), source_id text not null, sha256 text not null, revision_id text not null,
  split text not null check (split in ('train','validation','test')),
  primary key (dataset_id, source_id)
);
create table if not exists pipeline_predictions(
  id text primary key, run_id text not null, pipeline_version text not null, payload text not null, digest text not null,
  created_at text not null, unique (run_id, pipeline_version)
);
create table if not exists evaluation_runs(
  id text primary key, dataset_id text not null references dataset_versions(id), prediction_id text not null references pipeline_predictions(id),
  evaluator_version text not null, params text not null, report text not null, digest text not null, created_at text not null
);
create table if not exists edl_records(
  id text primary key, output_id text not null, run_id text not null, source_id text, payload text not null, digest text not null,
  created_at text not null, unique (output_id, digest)
);
create table if not exists editing_reports(
  id text primary key, edl_id text, revision_id text, evaluator_version text not null, report text not null, digest text not null, created_at text not null
);
create table if not exists crop_proposals(
  id text primary key, source_id text not null, status text not null check (status in ('proposal','approved')), payload text not null, created_at text not null
);
create table if not exists audit_log(
  id bigint generated by default as identity primary key, at text not null, actor text not null, action text not null, subject text, detail text
);

-- ---- Append-only / protected rows, enforced in the database (not only in application code) ----
create or replace function reject_append_only() returns trigger language plpgsql as $$
begin raise exception 'IMMUTABLE: % is append-only', tg_table_name using errcode = 'P0001'; end $$;
create or replace function reject_delete_protected() returns trigger language plpgsql as $$
begin raise exception 'PROTECTED: % rows are never deleted', tg_table_name using errcode = 'P0001'; end $$;
create or replace function reject_identity_change() returns trigger language plpgsql as $$
begin raise exception 'IMMUTABLE: source identity' using errcode = 'P0001'; end $$;

do $$
declare t text;
begin
  foreach t in array array['annotation_revisions','dataset_versions','dataset_members','pipeline_predictions','evaluation_runs',
                           'edl_records','editing_reports','crop_proposals','audit_log'] loop
    execute format('drop trigger if exists %I on %I', t || '_append_only', t);
    execute format('create trigger %I before update or delete on %I for each row execute function reject_append_only()', t || '_append_only', t);
  end loop;
  foreach t in array array['sources','athletes','source_locations','upload_occurrences'] loop
    execute format('drop trigger if exists %I on %I', t || '_protected', t);
    execute format('create trigger %I before delete on %I for each row execute function reject_delete_protected()', t || '_protected', t);
  end loop;
end $$;
drop trigger if exists sources_identity_frozen on sources;
create trigger sources_identity_frozen before update of id, sha256, byte_size on sources
  for each row execute function reject_identity_change();

-- ---- Evaluator boundary: frozen data only ----
create or replace view frozen_revisions as
  select m.dataset_id, m.split, m.sha256, r.id as revision_id, r.digest, r.content
  from dataset_members m join annotation_revisions r on r.id = m.revision_id;
create or replace view frozen_datasets as
  select id, name, created_at, digest, manifest from dataset_versions;

insert into meta(key, value) values ('schema_version', '1') on conflict (key) do nothing;
insert into schema_migrations(version) values ('0001_ground_truth') on conflict (version) do nothing;
