#!/usr/bin/env python3
"""Copy the app's legal texts to the web API so the stores get public URLs (/legal/privacy, /legal/terms).

Source of truth: mobile/src/shared/legal/{privacyPolicy,terms}.ts. The web copy is generated, never edited.
  python3 scripts/sync_legal_text.py          write web-api/src/content/legal.generated.ts
  python3 scripts/sync_legal_text.py --check  fail when the web copy differs from the app's text
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "PRIVACY_POLICY": ROOT / "mobile/src/shared/legal/privacyPolicy.ts",
    "TERMS_OF_SERVICE": ROOT / "mobile/src/shared/legal/terms.ts",
}
TARGET = ROOT / "web-api/src/content/legal.generated.ts"


def extract(name: str, path: Path) -> str:
    match = re.search(rf"export const {name} = `(.*?)`\.trim\(\);", path.read_text(encoding="utf-8"), re.S)
    if not match:
        raise SystemExit(f"{path}: template literal {name} not found")
    body = match.group(1)
    if "${" in body:
        raise SystemExit(f"{path}: {name} must stay a plain text literal (no interpolation)")
    return body


def render() -> str:
    parts = ["// GENERATED by scripts/sync_legal_text.py from mobile/src/shared/legal. Do not edit.\n"]
    for name, path in SOURCES.items():
        parts.append(f"export const {name} = `{extract(name, path)}`.trim();\n")
    return "\n".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            raise SystemExit("web-api legal text is out of date: run python3 scripts/sync_legal_text.py")
        print("legal text in sync (app and web)")
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
